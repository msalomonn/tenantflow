import { Pool } from 'pg';
import { getMigrations } from 'better-auth/db/migration';
import { readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

function required(name:string) { const v=process.env[name]; if(!v) throw new Error(`Missing ${name}`); return v; }
const pool = new Pool({connectionString:required('DATABASE_ADMIN_URL')});
const authMigrationPool = new Pool({connectionString:required('DATABASE_ADMIN_URL'),options:'-c search_path=auth'});
const client=await pool.connect();
try {
  await client.query("SELECT pg_advisory_lock(hashtext('tenantflow-migrations'))");
  await client.query('CREATE SCHEMA IF NOT EXISTS auth; REVOKE ALL ON SCHEMA auth FROM PUBLIC; REVOKE CREATE ON SCHEMA public FROM PUBLIC;');
  for (const [role,key] of [['tenantflow_app','APP_DB_PASSWORD'],['tenantflow_auth','AUTH_DB_PASSWORD']]) {
    const password=required(key);
    if(!/^[a-f0-9]{48}$/.test(password)) throw new Error(`${key} must be a 48-character hex value generated by setup`);
    const found=await client.query('SELECT 1 FROM pg_roles WHERE rolname=$1',[role]);
    if (!found.rowCount) await client.query(`CREATE ROLE ${role} LOGIN PASSWORD '${password}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE`);
  }
  const authMigration=await getMigrations({database:authMigrationPool,emailAndPassword:{enabled:true}});
  await authMigration.runMigrations();
  await client.query('GRANT USAGE ON SCHEMA auth TO tenantflow_auth; GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA auth TO tenantflow_auth; GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA auth TO tenantflow_auth;');
  await client.query('CREATE TABLE IF NOT EXISTS public.schema_migrations (name text PRIMARY KEY, sha256 text NOT NULL, applied_at timestamptz NOT NULL DEFAULT now())');
  for (const name of (await readdir('db/migrations')).filter(n=>n.endsWith('.sql')).sort()) {
    const sql=await readFile(`db/migrations/${name}`,'utf8');
    const sha=createHash('sha256').update(sql).digest('hex');
    const row=await client.query('SELECT sha256 FROM public.schema_migrations WHERE name=$1',[name]);
    if(row.rowCount) { if(row.rows[0].sha256!==sha) throw new Error(`Applied migration changed: ${name}`); continue; }
    await client.query('BEGIN');
    try { await client.query(sql); await client.query('INSERT INTO public.schema_migrations(name,sha256) VALUES($1,$2)',[name,sha]); await client.query('COMMIT'); }
    catch(e) { await client.query('ROLLBACK'); throw e; }
    console.log(`Applied ${name}`);
  }
  console.log('Migrations complete; runtime roles have no schema ownership or DDL privileges.');
} finally {
  await client.query("SELECT pg_advisory_unlock(hashtext('tenantflow-migrations'))");
  client.release(); await pool.end(); await authMigrationPool.end();
}
